// from the app. Run:  npx vite-node scripts/gen-schema.ts
import { writeFileSync } from "node:fs";
import { TABLES, WRITE_AREAS, fieldsOf, snake, sqlType } from "../src/lib/tables";

const out: string[] = ["-- GENERATED by scripts/gen-schema.ts from src/lib/schema.ts – do not edit by hand.", ""];
const policyAreas = (c: string) => WRITE_AREAS[c].map((a) => `public.can_write(farm_id, '${a}')`).join(" or ");

for (const [collection, table] of Object.entries(TABLES)) {
  const cols = fieldsOf(collection).map((f) => {
    const fk = f.type === "ref" ? ` references public.${TABLES[f.ref!]}(id) on delete set null` : "";
    return `  ${snake(f.key)} ${sqlType(f.type)}${fk}`;
  });
  out.push(
    `create table public.${table} (`,
    `  id uuid primary key default gen_random_uuid(),`,
    `  farm_id uuid not null references public.farms(id) on delete cascade,`,
    ...cols.map((c) => c + ","),
    `  extra jsonb not null default '{}'::jsonb,`,
    `  created_at timestamptz not null default now(),`,
    `  updated_at timestamptz not null default now(),`,
    `  deleted_at timestamptz`,
    `);`,
    `create index on public.${table} (farm_id, updated_at);`,
    `create trigger ${table}_touch before insert or update on public.${table} for each row execute function public.touch_row();`,
    `alter table public.${table} enable row level security;`,
    `create policy ${table}_read on public.${table} for select using (public.farm_role_of(farm_id) is not null);`,
    `create policy ${table}_insert on public.${table} for insert with check (${policyAreas(collection)});`,
    `create policy ${table}_update on public.${table} for update using (${policyAreas(collection)}) with check (${policyAreas(collection)});`,
    `-- no delete policy: rows are soft-deleted (deleted_at) so other devices learn about the deletion`,
    "",
  );
}
out.push("create unique index animals_farm_tag_uniq on public.animals (farm_id, lower(tag)) where deleted_at is null;", "");
out.push(
  "-- One round trip to fetch everything that changed on a farm (RLS applies: runs as the caller).",
  "create or replace function public.farm_changes(f uuid, since timestamptz default null, lim int default 5000) returns jsonb language plpgsql stable as $fn$",
  "declare t text; r jsonb; res jsonb := '{}'::jsonb; more jsonb := '[]'::jsonb;",
  "begin",
  `  foreach t in array array[${Object.values(TABLES).map((t) => `'${t}'`).join(",")}] loop`,
  "    execute format('select coalesce(jsonb_agg(to_jsonb(x) order by x.updated_at, x.id), ''[]''::jsonb) from (select * from public.%I where farm_id = $1 and ((($2)::timestamptz is null and deleted_at is null) or updated_at >= ($2)::timestamptz) order by updated_at, id limit $3) x', t) into r using f, since, lim + 1;",
  "    if jsonb_array_length(r) > lim then more := more || to_jsonb(t); r := r - lim; end if;",
  "    if jsonb_array_length(r) > 0 then res := res || jsonb_build_object(t, r); end if;",
  "  end loop;",
  "  return jsonb_build_object('tables', res, 'more', more);",
  "end $fn$;",
  "",
);
writeFileSync("supabase/migrations/20261012000100_farm_tables.sql", out.join("\n"));
console.log(`generated ${Object.keys(TABLES).length} tables`);
